@tool("search_email",
      "Search the user's Gmail. Supports Gmail search syntax, e.g. 'is:unread newer_than:2d', 'from:amazon', "
      "'subject:invoice after:2026/09/01'. Returns sender, subject, date and a snippet for each match.",
      {"query": {"type": "string"}, "max": {"type": "integer", "minimum": 1, "maximum": 10}},
      ["query"], needs="gmail.readonly")
async def search_email(ctx: ToolCtx, args: dict) -> str:
    from app import google
    found = await google.search_email(args["query"], args.get("max", 5))
    return google.wrap("gmail", found) if found else "no emails matched"


@tool("read_email", "Read one email's full text by its id (from search_email).",
      {"message_id": {"type": "string"}}, ["message_id"], needs="gmail.readonly")
async def read_email(ctx: ToolCtx, args: dict) -> str:
    from app import google
    return google.wrap("gmail", await google.read_email(args["message_id"]))


def _render_email(a: dict) -> str:
    head = f"Send email to {', '.join(a['to'])}\nSubject: {a['subject']}"
    if a.get("reply_to_message_id"):
        head += "\n(reply in the same thread)"
    return f"{head}\n---\n{a['body']}"


@tool("send_email",
      "Send an email from the user's Gmail, or reply in a thread (pass reply_to_message_id). The user must approve "
      "it with a button before it is sent; write the exact final text.",
      {"to": {"type": "array", "items": {"type": "string", "format": "email"}, "minItems": 1, "maxItems": 5},
       "subject": {"type": "string", "maxLength": 200},
       "body": {"type": "string", "maxLength": 5000},
       "reply_to_message_id": {"type": "string"}},
      ["to", "subject", "body"], tier="WO", needs="gmail.send", render=_render_email)
async def send_email(ctx: ToolCtx, args: dict) -> dict:
    from app import google
    return await google.send_email(args["to"], args["subject"], args["body"], args.get("reply_to_message_id"))


# ---------------------------------------------------------------- browser (T-29, T-30)

def _render_browser(a: dict) -> str:
    start = a.get("start_url") or "agent decides"
    return f"Do this in your browser:\n{a['goal']}\n(start: {start})"


@tool("browser_task",
      "Use the user's own browser to do something on ANY website. mode 'read' only looks (search, read, check); "
      "mode 'act' submits, posts, sends, buys or changes something and needs the user's approval. Give ONE clear goal, "
      "and a start_url if you know it. If a login, CAPTCHA or 2FA blocks it, the user is asked to take over.",
      {"goal": {"type": "string", "maxLength": 500},
       "mode": {"type": "string", "enum": ["read", "act"]},
       "start_url": {"type": "string", "pattern": "^https?://"}},
      ["goal", "mode"], tier=lambda a: "WO" if a["mode"] == "act" else "R", queue="browser",
      render=_render_browser, limit_key=lambda a: f"browser_task:{a['mode']}")
async def browser_task(ctx: ToolCtx, args: dict) -> dict:
    from app import browser, telegram
    from app.activities import TAKEOVER_TTL, request_approval
    from app.agent import guard
    from app.config import get_settings

    async def on_action(name, shown, result, url):
        await guard.audit("browser_action", "executed" if result == "ok" else "failed", turn_id=ctx.turn_id or None,
                          detail={"action": name, "args": shown, "result": result, "url": url[:300]})

    r = await browser.run_browser_task(args["goal"], args["mode"], args.get("start_url"), on_action=on_action)
    if r["status"] == "needs_user":
        await request_approval(ctx.turn_id or None, "takeover", args,
                               f"{r['reason']}.\nOpen your browser here: {get_settings().live_view_url}\n"
                               "Tap Done when you've finished.", ttl=TAKEOVER_TTL, kind="take")
        return {"status": "needs_user", "reason": r["reason"],
                "note": "The user was sent the live-view link and a Done button. Tell them briefly and wait."}
    if r["status"] == "failed":
        raise ToolError(f"browser task failed: {r['reason']}")
    if r.get("screenshot"):
        await telegram.send_photo(r["screenshot"], caption=args["goal"][:200], turn_id=ctx.turn_id or None)
    return {"status": "done", "result": untrusted_browser(r["summary"]), "user_text": r["summary"]}


def untrusted_browser(text: str) -> str:
    from app.agent.context import untrusted
    return untrusted("browser", text)


# ---------------------------------------------------------------- scheduled tasks (T-32..T-34), stored in Temporal

def _local(dt) -> str:
    from app.config import get_settings
    return dt.astimezone(get_settings().owner_timezone).strftime("%a %d %b %H:%M")


@tool("schedule_task",
      "Schedule something for later. kind 'remind' = send the user a reminder message with `text`. kind 'do' = at that "
      "time YOU perform `text` as an instruction (e.g. 'check Hacker News and send me the top 5'). Give fire_at (ISO 8601 "
      "with offset, one time) OR cron (5 fields, repeating, user's timezone, e.g. '0 9 * * MON').",
      {"kind": {"type": "string", "enum": ["remind", "do"]},
       "text": {"type": "string", "minLength": 1, "maxLength": 300},
       "fire_at": {"type": "string"},
       "cron": {"type": "string"}},
      ["kind", "text"], tier="WS")
async def schedule_task(ctx: ToolCtx, args: dict) -> str:
    import secrets
    from datetime import datetime, timedelta, timezone

    from temporalio.client import (Schedule, ScheduleActionStartWorkflow, ScheduleOverlapPolicy, SchedulePolicy,
                                   ScheduleSpec)

    from app.clients import temporal
    from app.config import get_settings
    from app.workflows import ScheduledTaskWorkflow, TaskFireWorkflow

    if bool(args.get("fire_at")) == bool(args.get("cron")):
        raise ToolError("give exactly one of fire_at (one time) or cron (repeating)")
    task_id = f"task-{secrets.token_hex(4)}"
    task = {"id": task_id, "kind": args["kind"], "text": args["text"]}
    client = await temporal()
    now = datetime.now(timezone.utc)

    if fire_at := args.get("fire_at"):
        try:
            when = datetime.fromisoformat(fire_at)
        except ValueError:
            raise ToolError("fire_at must be ISO 8601, e.g. 2026-10-03T08:00:00+05:30") from None
        if when.tzinfo is None:
            raise ToolError("fire_at needs a timezone offset, e.g. +05:30")
        if not now + timedelta(seconds=30) < when < now + timedelta(days=366):
            raise ToolError("fire_at must be at least 30 seconds and at most a year from now")
        task["fire_at"] = when.isoformat()
        await client.start_workflow(ScheduledTaskWorkflow.run, task, id=task_id, task_queue="agent",
                                    memo={"kind": task["kind"], "text": task["text"], "when": task["fire_at"]})
        return f"Scheduled [{task_id}] for {_local(when)}"

    cron = " ".join(args["cron"].split())
    if len(cron.split()) != 5:
        raise ToolError("cron needs exactly 5 fields: minute hour day-of-month month day-of-week")
    s = get_settings()
    try:
        handle = await client.create_schedule(
            task_id,
            Schedule(action=ScheduleActionStartWorkflow(TaskFireWorkflow.run, task, id=f"{task_id}-run", task_queue="agent"),
                     spec=ScheduleSpec(cron_expressions=[cron], time_zone_name=str(s.owner_timezone)),
                     policy=SchedulePolicy(overlap=ScheduleOverlapPolicy.SKIP, catchup_window=timedelta(hours=1))),
            memo={"kind": task["kind"], "text": task["text"], "when": cron})
    except Exception as e:
        raise ToolError(f"invalid cron {cron!r}: {e}") from e
    upcoming = (await handle.describe()).info.next_action_times[:2]
    min_gap = timedelta(minutes=s.recurring_do_min_minutes if args["kind"] == "do" else 1)
    if len(upcoming) == 2 and upcoming[1] - upcoming[0] < min_gap:
        await handle.delete()
        raise ToolError(f"repeating '{args['kind']}' tasks can run at most every {min_gap} (each 'do' run uses AI requests)")
    first = f", first at {_local(upcoming[0])}" if upcoming else ""
    return f"Scheduled [{task_id}] repeating '{cron}' ({s.owner_timezone}){first}"


@tool("list_tasks", "List scheduled tasks (one-time and repeating) and pending approvals.", {}, [])
async def list_tasks(ctx: ToolCtx, args: dict) -> dict:
    from datetime import datetime

    from app.clients import temporal
    client = await temporal()
    items = []
    async for wf in client.list_workflows('WorkflowType = "ScheduledTaskWorkflow" AND ExecutionStatus = "Running"'):
        m = await wf.memo()
        items.append(f"[{wf.id}] {m.get('kind')} · {_local(datetime.fromisoformat(m['when']))} · {m.get('text')!r}")
    async for sc in await client.list_schedules():
        m = await sc.memo()
        if sc.id.startswith("task-"):
            items.append(f"[{sc.id}] {m.get('kind')} · repeating '{m.get('when')}' · {m.get('text')!r}")
    rows = await db.fetchall("SELECT tool, summary FROM approvals WHERE status = 'pending' AND expires_at > now()")
    items += [f"waiting for your tap: {r['summary'].splitlines()[0]}" for r in rows]
    return {"tasks": items or ["nothing scheduled"]}


@tool("cancel_task", "Cancel a scheduled task by its id, e.g. task-1a2b3c4d.",
      {"task_id": {"type": "string", "pattern": "^task-[0-9a-f]{8}$"}}, ["task_id"], tier="WS")
async def cancel_task(ctx: ToolCtx, args: dict) -> str:
    from temporalio.service import RPCError

    from app.clients import temporal
    client = await temporal()
    try:
        await client.get_workflow_handle(args["task_id"]).cancel()
        return f"cancelled {args['task_id']}"
    except RPCError:
        pass
    try:
        await client.get_schedule_handle(args["task_id"]).delete()
        return f"cancelled repeating {args['task_id']}"
    except RPCError:
        return f"{args['task_id']} was already gone"
