"""Tool registry: what the model can call, how risky it is, what it needs, and which worker runs it.

Tiers: R = read · WS = write to self · WO = write to others / public (approval) · D = destructive (approval).
Handlers are `async def handler(ctx, args) -> str | dict`. They raise ToolError for problems the model should see.
Heavy modules (Gmail, browser, Temporal) are imported inside handlers so every worker can load this registry.
"""

from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field

from app import db


class ToolError(Exception):
    """A problem the model should be told about (becomes an error tool result, not a crash)."""


@dataclass(frozen=True)
class ToolCtx:
    turn_id: str
    tool_call_id: str


@dataclass(frozen=True)
class Tool:
    name: str
    description: str
    properties: dict
    required: tuple[str, ...]
    handler: Callable[[ToolCtx, dict], Awaitable[str | dict]]
    tier: str | Callable[[dict], str] = "R"
    needs: str | None = None          # e.g. "gmail.readonly", "gmail.send"
    queue: str = "agent"
    render: Callable[[dict], str] | None = None   # approval text, generated by code from the input
    limit_key: Callable[[dict], str] | None = None  # which rate-limit bucket a call counts against
    extra: dict = field(default_factory=dict)

    @property
    def schema(self) -> dict:
        return {"type": "object", "properties": self.properties, "required": list(self.required),
                "additionalProperties": False}

    def tier_for(self, args: dict) -> str:
        return self.tier(args) if callable(self.tier) else self.tier


TOOLS: dict[str, Tool] = {}


def tool(name, description, properties, required=(), **kw):
    def register(fn):
        TOOLS[name] = Tool(name, description, properties, tuple(required), fn, **kw)
        return fn
    return register


def definitions(names: list[str]) -> list[dict]:
    """The `tools` array for the model (OpenAI function format), in the given (sorted) order."""
    return [{"type": "function", "function": {"name": n, "description": TOOLS[n].description,
                                              "parameters": TOOLS[n].schema}} for n in names]


GMAIL_SCOPE = "https://www.googleapis.com/auth/"


def need_met(need: str | None, connections: dict[str, dict]) -> bool:
    if need is None:
        return True
    if need.startswith("gmail."):
        g = connections.get("google")
        return bool(g and g["status"] == "connected" and GMAIL_SCOPE + need in g["scopes"])
    return False


def menu_for(connections: dict[str, dict]) -> list[str]:
    """Tool names usable right now, sorted so the list is byte-stable between turns."""
    return sorted(n for n, t in TOOLS.items() if need_met(t.needs, connections))


async def load_connections() -> dict[str, dict]:
    rows = await db.fetchall("SELECT provider, status, scopes, meta FROM connections")
    return {r["provider"]: r for r in rows}


# ---------------------------------------------------------------- core tools

@tool("react_to_message", "React to the user's latest message with one emoji, e.g. 👀 when a task will take a while.",
      {"emoji": {"type": "string", "description": "A single emoji, e.g. 👀 👍 ❤️ 🔥 👌"}}, ["emoji"], tier="WS")
async def react_to_message(ctx: ToolCtx, args: dict) -> str:
    from app import telegram
    row = await db.fetchone(
        "SELECT tg_message_id FROM messages WHERE direction = 'in' AND kind = 'text' ORDER BY id DESC LIMIT 1")
    if not row:
        raise ToolError("no message to react to")
    try:
        await telegram.set_reaction(row["tg_message_id"], args["emoji"])
    except telegram.Permanent as e:
        raise ToolError(f"Telegram refused that reaction (use a common emoji): {e}") from e
    return "reacted"


# ---------------------------------------------------------------- memory (T-15, T-16)

@tool("remember_fact",
      "Save a durable personal fact the user told you (a preference, a person, a place, a routine) so you remember "
      "it in future conversations. Not for small talk or one-off details.",
      {"kind": {"type": "string", "enum": ["preference", "person", "place", "other"]},
       "content": {"type": "string", "maxLength": 300, "description": "The fact, short and self-contained"}},
      ["kind", "content"], tier="WS")
async def remember_fact(ctx: ToolCtx, args: dict) -> dict:
    content = " ".join(args["content"].split())
    if not content:
        raise ToolError("empty fact")
    src = await db.fetchone("SELECT id FROM messages WHERE direction = 'in' ORDER BY id DESC LIMIT 1")
    row = await db.fetchone(
        "INSERT INTO memory_facts (kind, content, source_message_id) VALUES (%s, %s, %s)"
        " ON CONFLICT (lower(btrim(content))) DO UPDATE SET updated_at = now(), kind = EXCLUDED.kind RETURNING id",
        (args["kind"], content, src["id"] if src else None))
    return {"saved": f"f{row['id']}"}


@tool("forget_fact", "Delete a remembered fact by its id (shown as [f12] in <facts>), when the user asks or it's wrong.",
      {"fact_id": {"type": "string", "pattern": "^f?[0-9]+$", "description": "e.g. f12"}}, ["fact_id"], tier="WS")
async def forget_fact(ctx: ToolCtx, args: dict) -> str:
    n = await db.execute("DELETE FROM memory_facts WHERE id = %s", (int(args["fact_id"].lstrip("f")),))
    if not n:
        raise ToolError(f"no fact {args['fact_id']}")
    return "forgotten"


@tool("search_history",
      "Search older conversations and remembered facts by keywords, when the user refers to something from the past "
      "that isn't in <recent_messages>. Use distinctive words (names, places, things).",
      {"query": {"type": "string", "minLength": 1}, "limit": {"type": "integer", "minimum": 1, "maximum": 10}},
      ["query"])
async def search_history(ctx: ToolCtx, args: dict) -> dict:
    from app.config import get_settings
    tz = get_settings().owner_timezone
    q, limit = args["query"], args.get("limit", 8)
    # OR the words together: a short keyword query should match messages with any of them, ranked by relevance.
    words = [w for w in q.replace('"', " ").split() if w.lower() not in {"or", "and", "the", "a"}]
    tsq = " OR ".join(words) or q
    rows = await db.fetchall(
        "SELECT * FROM ("
        " SELECT 'message' AS src, direction, sent_at AS at, body AS text,"
        "  ts_rank(tsv, websearch_to_tsquery('simple', %(q)s)) AS rank FROM messages"
        "  WHERE kind = 'text' AND tsv @@ websearch_to_tsquery('simple', %(q)s)"
        " UNION ALL"
        " SELECT 'fact', 'fact', updated_at, content, ts_rank(tsv, websearch_to_tsquery('simple', %(q)s)) + 1"
        "  FROM memory_facts WHERE tsv @@ websearch_to_tsquery('simple', %(q)s)"
        ") hits ORDER BY rank DESC, at DESC LIMIT %(n)s", {"q": tsq, "n": limit})
    if not rows:
        return {"results": [], "note": "nothing found; try other keywords"}
    who = {"in": "User", "out": "You", "fact": "Fact"}
    return {"results": [f"[{r['at'].astimezone(tz):%Y-%m-%d %H:%M}] {who[r['direction']]}: {r['text'][:400]}" for r in rows]}


